describe("environment", function()
	it("runs under LuaJIT with the flake's modules", function()
		assert.is_table(jit)
		assert.truthy(require("cjson"))
		assert.truthy(require("lfs"))
		assert.truthy(require("sqlite"))
	end)
end)

describe("random's LuaJIT DRBG (flake input)", function()
	it("is importable, seedable and resumable from a state snapshot", function()
		local drbg = require("drbg")
		local seed = string.rep("\0", 31) .. string.char(42)
		local a, b = drbg.new(seed), drbg.new(seed)
		assert.equal(a:bytes(16), b:bytes(16))
		local resumed = drbg.from_state(a:state())
		assert.equal(a:bytes(8), resumed:bytes(8))
		local u = a:uniform_number()
		assert.is_true(u >= 0 and u < 1)
	end)
end)
